"""tools/cyclara_demo_data.py: compact data for the Cyclara page's live figure, from Cyclara's own analysis of the synthetic demonstration file.

Input: the output folder of
  python -m electrochem.analyze data/demo/cyclara_demo_synthetic.mpt --charge ox --reference "Li+/Li" \
      --mass-mg 5 --molar-mass 214.4 --electrons 1 --cycles 1,...,50 --plots none --no-prompt --no-origin
Output: assets/js/cyclara-demo.js, window.CYCLARA_DEMO = {...}
Curves are simplified with Ramer-Douglas-Peucker in axis-normalised units (tolerance 0.0015 of each axis
range), which keeps every visible bend; numbers are the engine's own, rounded for display.
"""
import csv, json, sys
from collections import defaultdict
from pathlib import Path

run, out = Path(sys.argv[1]), Path(sys.argv[2])
curves = defaultdict(lambda: {"charge": [], "discharge": []})
with open(run / "curves_potential_capacity.csv", newline="") as f:
    for r in csv.DictReader(f):
        curves[int(r["cycle"])][r["direction"]].append((float(r["capacity_basis"]), float(r["potential_V"])))
cycles = {}
with open(run / "cycles.csv", newline="") as f:
    for r in csv.DictReader(f):
        cycles[int(r["cycle"])] = r

xs = [x for c in curves.values() for b in c.values() for x, _ in b]
ys = [y for c in curves.values() for b in c.values() for _, y in b]
xr, yr = max(xs) - min(xs), max(ys) - min(ys)

def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = (x1 - x0) / xr, (y1 - y0) / yr
    norm = (dx * dx + dy * dy) ** 0.5 or 1e-12
    best, idx = -1.0, 0
    for i in range(1, len(pts) - 1):
        px, py = (pts[i][0] - x0) / xr, (pts[i][1] - y0) / yr
        d = abs(px * dy - py * dx) / norm
        if d > best:
            best, idx = d, i
    if best <= eps:
        return [pts[0], pts[-1]]
    return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)

data, npts = [], 0
for n in sorted(curves):
    r = cycles[n]
    entry = {"n": n}
    for key, name in (("c", "charge"), ("d", "discharge")):
        pts = rdp(curves[n][name], 0.0015)
        npts += len(pts)
        entry[key] = [v for x, y in pts for v in (round(x * 10), round(y * 1000))]   # 0.1 mAh/g, mV
    entry["qc"] = round(float(r["charge_specific_mAh_g"]), 2)
    entry["qd"] = round(float(r["discharge_specific_mAh_g"]), 2)
    entry["ce"] = round(float(r["coulombic_efficiency_pct"]), 3)
    entry["vd"] = round(float(r["average_discharge_voltage_V"]), 4)
    entry["vc"] = round(float(r["average_charge_voltage_V"]), 4)
    entry["ret"] = round(float(r["capacity_retention_pct"]), 2)
    data.append(entry)

summary = json.loads((run / "summary.json").read_text())
payload = {"source": "data/demo/cyclara_demo_synthetic.mpt (synthetic), analysed by Cyclara 0.8.0",
           "summary": {"cycles": summary["complete_cycles"],
                       "first_qd": round(summary["first_cycle_specific_discharge_mAh_g"], 2),
                       "first_ce": round(summary["first_cycle_coulombic_efficiency_pct"], 2),
                       "ret_last": round(summary["retention_at_last_cycle_pct"], 2),
                       "mean_ce": round(summary["mean_coulombic_efficiency_pct"], 2),
                       "mean_vd": round(summary["mean_average_discharge_voltage_V"], 3)},
           "mass_mg": 5, "x": "specific capacity / mAh g-1 (x10)", "y": "potential vs Li+/Li / mV", "cycles": data}
js = ("/* The live figure on /cyclara/: Cyclara's own analysis of its synthetic demonstration file (50 cycles).\n"
      "   Generated by tools/cyclara_demo_data.py from the analysis folder; curves simplified for display, numbers the engine's. */\n"
      "window.CYCLARA_DEMO=" + json.dumps(payload, separators=(",", ":")) + ";\n")
out.write_text(js)
print(f"{len(data)} cycles, {npts} points kept of {len(xs)}, {len(js.encode())} bytes; x 0..{max(xs):.1f}, y {min(ys):.3f}..{max(ys):.3f}")
